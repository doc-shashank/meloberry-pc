using System.Text;
using Meloberry.Wrapper.Domain.Models;

namespace Meloberry.Wrapper.Domain.Services;

/// <summary>
/// Deterministically renders a lean, targeted <c>AGENTS.md</c> file tailored to the Active Workspace
/// and the user's selected shopping-list specs so AI agents start work without discovery turns.
/// </summary>
public static class AgentsMdComposer
{
    /// <summary>
    /// BPE-aware deterministic token estimator (words, digits, symbols, and newlines),
    /// closely tracking modern LLM tokenizers without pulling heavy native dependencies.
    /// </summary>
    public static int EstimateTokens(string text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return 0;
        }

        var tokens = 0;
        var i = 0;
        while (i < text.Length)
        {
            var ch = text[i];
            if (ch == ' ' || ch == '\t' || ch == '\r')
            {
                // Single leading space attaches to the following word in BPE; count extra whitespace runs lightly.
                var run = 0;
                while (i < text.Length && (text[i] == ' ' || text[i] == '\t' || text[i] == '\r'))
                {
                    run++;
                    i++;
                }

                if (run > 1)
                {
                    tokens += Math.Max(1, (run - 1) / 4);
                }

                continue;
            }

            if (ch == '\n')
            {
                tokens++;
                i++;
                continue;
            }

            if (char.IsLetter(ch))
            {
                var start = i;
                while (i < text.Length && char.IsLetter(text[i]))
                {
                    i++;
                }

                var len = i - start;
                tokens += len <= 6 ? 1 : (int)Math.Ceiling(len / 4.5);
                continue;
            }

            if (char.IsDigit(ch))
            {
                var start = i;
                while (i < text.Length && char.IsDigit(text[i]))
                {
                    i++;
                }

                var len = i - start;
                tokens += Math.Max(1, (int)Math.Ceiling(len / 3.0));
                continue;
            }

            // Group repeated identical punctuation (e.g. "###", "---", "```") as one token.
            var punct = ch;
            while (i < text.Length && text[i] == punct)
            {
                i++;
            }

            tokens++;
        }

        return Math.Max(1, tokens);
    }

    public static string Compose(AgentsMdComposeInput input)
    {
        ArgumentNullException.ThrowIfNull(input);

        var sb = new StringBuilder();
        var mbyCmd = input.UsesWorkspaceShim
            ? ".\\mby-pc.bat mby"
            : FormatCliCommand(input.WorkspaceMbyFileName, "mby");
        var melomgCmd = input.UsesWorkspaceShim
            ? ".\\mby-pc.bat melomg"
            : FormatCliCommand(input.WorkspaceMelomgFileName, "melomg");

        sb.AppendLine("# AGENTS.md — Meloberry Active Workspace Contract");
        sb.AppendLine();
        sb.AppendLine("This file was generated by **Meloberry PC** for this Active Workspace. Use the exact executables, files, and live CLI schemas below directly—do not spend extra turns running `prime` or `spec` unless you intentionally branch outside these selections.");
        sb.AppendLine();

        AppendToolsetAndFilesSection(sb, input, mbyCmd, melomgCmd);
        AppendExecutionContractSection(sb, input, mbyCmd, melomgCmd);
        AppendWorkflowSection(sb, input, mbyCmd, melomgCmd);
        AppendTargetedSchemasSection(sb, input);
        AppendMelomgSpecsSection(sb, input, melomgCmd);

        return sb.ToString().TrimEnd() + Environment.NewLine;
    }

    internal static string FormatCliCommand(string? pathOrFileName, string fallback)
    {
        if (string.IsNullOrWhiteSpace(pathOrFileName))
        {
            return fallback;
        }

        var trimmed = pathOrFileName.Trim();
        if (trimmed.StartsWith(".\\", StringComparison.Ordinal) || trimmed.StartsWith("./", StringComparison.Ordinal))
        {
            return trimmed;
        }

        if (Path.IsPathRooted(trimmed))
        {
            return trimmed.Contains(' ') ? $"& \"{trimmed}\"" : trimmed;
        }

        return $".\\{trimmed}";
    }

    internal static string MakeCodeFence(string? content)
    {
        if (string.IsNullOrEmpty(content))
        {
            return "```";
        }

        var maxRun = 0;
        var run = 0;
        foreach (var ch in content)
        {
            if (ch == '`')
            {
                run++;
                if (run > maxRun) maxRun = run;
            }
            else
            {
                run = 0;
            }
        }

        return new string('`', Math.Max(3, maxRun + 1));
    }

    private static void AppendToolsetAndFilesSection(
        StringBuilder sb,
        AgentsMdComposeInput input,
        string mbyCmd,
        string melomgCmd)
    {
        sb.AppendLine("## 1. Active Workspace Toolset & Staged Inputs");
        sb.AppendLine();
        sb.AppendLine($"- **Workspace Root**: `{input.WorkspacePath}`");
        sb.AppendLine($"- **`mby` CLI**: `{mbyCmd}`");
        if (!string.IsNullOrWhiteSpace(input.WorkspaceMelomgFileName))
        {
            sb.AppendLine($"- **`melomg` CLI**: `{melomgCmd}`");
        }

        foreach (var extraExe in input.ExtraWorkspaceExecutables.Where(x => !string.IsNullOrWhiteSpace(x)))
        {
            sb.AppendLine($"- **Additional Tool**: `{FormatCliCommand(extraExe, extraExe)}`");
        }

        if (input.CopiedFiles.Count > 0)
        {
            sb.AppendLine("- **Workspace Files (root)**: " + string.Join(", ", input.CopiedFiles.Select(f => $"`./{f}`")));
        }

        if (input.CopiedFolders.Count > 0)
        {
            sb.AppendLine("- **Workspace Subfolders**: " + string.Join(", ", input.CopiedFolders.Select(f => $"`./{f}/`")));
        }

        if (input.ExternalAttachments is { Count: > 0 })
        {
            sb.AppendLine("- **External Reference Files**: " + string.Join(", ", input.ExternalAttachments.Select(f => $"`{f}`")));
        }

        sb.AppendLine();
    }

    private static void AppendExecutionContractSection(
        StringBuilder sb,
        AgentsMdComposeInput input,
        string mbyCmd,
        string melomgCmd)
    {
        sb.AppendLine("## 2. Shared Execution Contract & Guardrails");
        sb.AppendLine();
        sb.AppendLine("- **Always enable agent JSON mode**: set `$env:MBY_AGENT='1'` (applies to both `mby` and `melomg`) or pass `--json`.");
        sb.AppendLine("- **Envelope & exit codes**: `exit 0` (`{\"success\":true,\"data\":...}`), `1` IO, `2` Validation/Lint, `3` NotFound, `4` Conflict, `5` Unauthorized.");
        sb.AppendLine("- **Pipe JSON via `stdin` (`-`)** for `apply`, `patch`, `add`, `build`, and `batch`. Quote `'@group'` args in PowerShell.");
        sb.AppendLine($"- **Addressing**: `<wsId>#c<n>`, `#c<n>.b<m>`, `#c<n>.q<m>`, `<setId>#q<m>`, `#<ref>` (`^[a-z0-9][a-z0-9_-]{{0,31}}$`).");
        sb.AppendLine("- **`mby` Strictness**: camelCase keys only (`disallowUnmappedProperties`); unknown keys fail with exit `2`. Every `imagePath` must be a **relative** path inside the JSON/Markdown directory and pass magic-byte validation (`.png/.jpg/.jpeg/.gif/.webp/.bmp/.svg`).");
        sb.AppendLine("- **Lint Invariants**: sessions need >=1 component; articles >=1 non-empty block; `table` widths & 1-based `hideableCols` must match; MCQs need 2..26 options & >=1 `isCorrect`; flashcards need non-empty text or image on both sides; `spot-error` needs >=2 `[span]` tokens.");
        sb.AppendLine("- **Never block on servers**: never launch `mby build --preview` or `mby layout edit` without `--no-wait`.");
        if (!string.IsNullOrWhiteSpace(input.WorkspaceMelomgFileName) || !string.IsNullOrWhiteSpace(input.MelomgSpecsText))
        {
            sb.AppendLine($"- **`melomg` Rules**: only `figure`, `diagram`, and `chart` categories exist (tables/equations excluded). Crop-only via `Windows.Data.Pdf`. Pass `--offline` in sandboxed/offline runs; use `--retain-db` if following up with `render`/`patch`/`mask`/`check` (invoke `{melomgCmd}`).");
        }

        sb.AppendLine();
    }

    private static void AppendWorkflowSection(
        StringBuilder sb,
        AgentsMdComposeInput input,
        string mbyCmd,
        string melomgCmd)
    {
        sb.AppendLine("## 3. Target Container & Build Commands");
        sb.AppendLine();
        sb.AppendLine($"- **Target Container**: {PromptComposer.FormatContainerLabel(input.Container)}");
        sb.AppendLine($"- **Authoring Format**: {PromptComposer.FormatAuthoringLabel(input.AuthoringFormat)}");

        if (!string.IsNullOrWhiteSpace(input.WorkspaceMelomgFileName))
        {
            sb.AppendLine($"- **PDF Extraction (if PDFs provided)**: `{melomgCmd} ingest ./source.pdf --retain-db --offline --quiet` -> inspect `anomalies[]`/`suspectPages[]` -> `{melomgCmd} extract <docId> all -o ./assets --quality high --manifest --quiet`.");
        }

        var sourceTarget = input.AuthoringFormat switch
        {
            AuthoringFormat.MarkdownDirectory => "./study_src/",
            AuthoringFormat.SingleMarkdown => "./study.md",
            _ => "./spec.json"
        };

        if (input.WorkflowMode == WorkflowMode.LiveAgent)
        {
            sb.AppendLine();
            sb.AppendLine("### Live GUI Control Protocol (`mby-pc.bat`)");
            sb.AppendLine("1. **Configure Metadata (Step 2 - Format)**: `.\\mby-pc.bat ui view format --json` -> `.\\mby-pc.bat draft patch --title \"...\" --desc \"...\" --container session|article|quiz --json`");
            sb.AppendLine("2. **Organize Cards & Specs (Step 3 - Organize)**: `.\\mby-pc.bat ui view organize --json` -> `.\\mby-pc.bat draft comp add|rename|move|rm` & `.\\mby-pc.bat draft spec add|update|move|rm`");
            sb.AppendLine("3. **Populate Spec Content Live**: `.\\mby-pc.bat draft spec set-content <specId> --raw \"...\" --json` (or `--file ./notes.md` or `--image assets/fig.png --caption \"...\"`)");
            sb.AppendLine("4. **Compile & Open Viewer (Step 4 -> Step 5)**: `.\\mby-pc.bat finalize --json` (builds via `mby batch -` and opens Step 5 Viewer automatically)");
            sb.AppendLine("> **Rule:** Prefer `draft` + `finalize` over calling `mby apply`/`mby build` directly so the GUI updates in real time.");
            sb.AppendLine();
        }

        sb.AppendLine($"- **One-Shot Compile & Verify**: `{mbyCmd} build {sourceTarget} -o ./dist_web --verify --json`");
        sb.AppendLine($"- **Persistent Workspace & Package Flow**: `{mbyCmd} apply {sourceTarget} --json` -> `{mbyCmd} check <wsId> --json` -> `{mbyCmd} build <wsId> -o ./dist_web --json` -> `{mbyCmd} pkg export <wsId> android ./out.mbypkg --json`");
        sb.AppendLine($"- **Headless QA**: `{mbyCmd} analyze ./dist_web --headless --json`");
        if (input.UsesWorkspaceShim && input.WorkflowMode != WorkflowMode.LiveAgent)
        {
            sb.AppendLine("- **Live Workspace Control (`mby-pc.bat`)**: `.\\mby-pc.bat status --json`, `.\\mby-pc.bat draft get --json`, `.\\mby-pc.bat draft spec set-content <specId> --raw \"...\" --json`, `.\\mby-pc.bat finalize --json`.");
        }
        sb.AppendLine();
    }

    private static void AppendTargetedSchemasSection(StringBuilder sb, AgentsMdComposeInput input)
    {
        sb.AppendLine("## 4. Targeted Live Schemas (`mby spec`)");
        sb.AppendLine();

        if (input.SelectedSpecs.Count == 0 && !input.IncludeLinkBlock)
        {
            sb.AppendLine("_No live `mby spec` schemas were attached (run `mby spec <topic> --json` after installing `mby`)._");
            sb.AppendLine();
            return;
        }

        foreach (var spec in input.SelectedSpecs)
        {
            sb.AppendLine($"### `{spec.Topic}` ({spec.Category})");
            if (!string.IsNullOrWhiteSpace(spec.Summary))
            {
                sb.AppendLine($"{spec.Summary}  ");
            }
            if (!string.IsNullOrWhiteSpace(spec.Command))
            {
                sb.AppendLine($"Command: `{spec.Command}`");
            }

            if (!string.IsNullOrWhiteSpace(spec.CompactSignature))
            {
                var sigFence = MakeCodeFence(spec.CompactSignature);
                sb.AppendLine($"{sigFence}text");
                sb.AppendLine(spec.CompactSignature.Trim());
                sb.AppendLine(sigFence);
            }

            if (spec.Fields.Count > 0)
            {
                sb.AppendLine("Fields:");
                foreach (var field in spec.Fields)
                {
                    var reqTag = field.Required ? "required" : "optional";
                    var constraints = new List<string>();
                    if (field.AllowedValues is { Count: > 0 })
                    {
                        constraints.Add("values: " + string.Join("|", field.AllowedValues));
                    }
                    if (field.MinValue.HasValue || field.MaxValue.HasValue)
                    {
                        constraints.Add($"range: {field.MinValue?.ToString() ?? ""}..{field.MaxValue?.ToString() ?? ""}");
                    }
                    if (field.MaxLength.HasValue)
                    {
                        constraints.Add($"maxLen: {field.MaxLength.Value}");
                    }
                    if (!string.IsNullOrWhiteSpace(field.Pattern))
                    {
                        constraints.Add($"pattern: `{field.Pattern}`");
                    }

                    var constraintText = constraints.Count > 0 ? $" ({string.Join(", ", constraints)})" : "";
                    sb.AppendLine($"- `{field.Name}` (`{field.Type}`, {reqTag}){constraintText}: {field.Description}");
                }
            }

            if (!string.IsNullOrWhiteSpace(spec.ExampleJson))
            {
                var exFence = MakeCodeFence(spec.ExampleJson);
                sb.AppendLine("<details><summary>Example JSON</summary>");
                sb.AppendLine();
                sb.AppendLine($"{exFence}json");
                sb.AppendLine(spec.ExampleJson.Trim());
                sb.AppendLine(exFence);
                sb.AppendLine("</details>");
            }

            sb.AppendLine();
        }

        if (input.IncludeLinkBlock)
        {
            var linkFence = MakeCodeFence(SpecCatalogDefaults.VirtualLinkTopic.CompactSignature);
            sb.AppendLine($"### `{SpecCatalogDefaults.VirtualLinkTopicName}` (block)");
            sb.AppendLine($"{SpecCatalogDefaults.VirtualLinkTopic.Summary}  ");
            sb.AppendLine($"Command: `{SpecCatalogDefaults.VirtualLinkTopic.Command}`");
            sb.AppendLine($"{linkFence}text");
            sb.AppendLine(SpecCatalogDefaults.VirtualLinkTopic.CompactSignature);
            sb.AppendLine(linkFence);
            sb.AppendLine();
        }
    }

    private static void AppendMelomgSpecsSection(StringBuilder sb, AgentsMdComposeInput input, string melomgCmd)
    {
        if (string.IsNullOrWhiteSpace(input.MelomgSpecsText) && string.IsNullOrWhiteSpace(input.WorkspaceMelomgFileName))
        {
            return;
        }

        sb.AppendLine("## 5. `melomg` PDF Extraction & Label Masking Reference");
        sb.AppendLine();
        if (!string.IsNullOrWhiteSpace(input.MelomgSpecsText))
        {
            var melFence = MakeCodeFence(input.MelomgSpecsText);
            sb.AppendLine($"{melFence}text");
            sb.AppendLine(input.MelomgSpecsText.Trim());
            sb.AppendLine(melFence);
        }
        else
        {
            sb.AppendLine($"Run `{melomgCmd} spec extract mask --json` if needed for full parameter flags.");
        }

        sb.AppendLine();
    }
}
